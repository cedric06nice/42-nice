#include <stdlib.h>

int ft_strlen(char *str)
{
	int i;

	i = 0;
	while (str[i])
		i++;
	return (i);
}

char *ft_strcat(char *dest, char *src)
{
	int i;
	int j;

	i = 0;
	j = 0;
	while (dest[j])
		j++;
	while (src[i])
	{
		dest[j + i] = src[i];
		i++;
	}
	dest[j + i] = '\0';
	return (dest);
}

char	*ft_strjoin(int size, char **strs, char *sep)
{
	int i;
	char	res_size;
	char	*res;

	i = 0;
	res_size = 0;
	res = NULL;
	if (size == 0)
		return ("");
	while (i < size)
	{
		res_size += ft_strlen(strs[i]);
		i++;
	}
	res_size += ft_strlen(sep) * (size - 1);
	res = malloc(sizeof(char) * res_size + 1);
	i = 0;
	while (i < size)
	{
		ft_strcat(res, strs[i]);
		if (i != size - 1)
			ft_strcat(res, sep);
		i++;
	}
	res[ft_strlen(res)] = 0;
	return (res);
}
