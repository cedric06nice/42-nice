#include <unistd.h>
#include <stdio.h>

void	ft_putstr(char *str)
{
	int	i;

	i = 0;
	while (str[i])
	{
		write(1, &str[i], 1);
		i++;
	}
}

int	ft_strlen(char *str)
{
	int	i;

	i = 0;
	while (str[i])
		i++;
	return (i);
}

int	main(int argc, char *argv[])
{
	int	i;

	i = argc;
	if (argc < 2)
		return (1);
	while (i > 1)
	{
		i--;
		ft_putstr(argv[i]);
		write(1, "\n", 1);
	}
	return (0);
}
